// Planning, cancelamento e anexos, de ponta a ponta no modo de teste (nenhum modelo é chamado).
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'work-ia-plan-'));
process.env.STUDIO_DATA = path.join(tmp, 'data'); process.env.STUDIO_PROJETOS = path.join(tmp, 'projetos'); process.env.STUDIO_FAKE = '1';
const store = await import('../lib/store.mjs');
store.gravarConfig({ piloto: { ativo: false, maxChamadasHora: 0 }, ciclo: { orcamento: 14, fechamento: false, statusPO: false, revisaoAuto: false, curadoriaAuto: false, versionar: false } });
const p = await import('../lib/projetos.mjs');
fs.mkdirSync(path.join(tmp, 'alvo'));
const r = p.criar({ nome: 'Planning', caminho: path.join(tmp, 'alvo'), template: 'software' }); assert(r.ok);
const c = p.ctx(r.projeto.id);
const espera = async (cond, ms = 20000) => { for (let t = 0; t < ms / 50 && !cond(); t++) await new Promise((x) => setTimeout(x, 50)); assert(cond(), 'tempo esgotado esperando a condição'); };

// A classificacao usa apenas ordens diretas sem ressalvas; nao e um detector de intencao geral.
const { autorizaExecucaoPlanning } = await import('../lib/equipe.mjs');
for (const texto of [
  'nao implemente nada',
  'implemente depois que eu autorizar',
  'planeje como implementar, sem executar',
  'planeje como implementar',
  'no pedido anterior eu escrevi "implemente a integracao"; planeje agora',
  'a mensagem anterior dizia implemente o sistema',
  'implemente somente depois da minha aprovacao',
  'execute se eu aprovar',
  'implemente, mas aguarde minha confirmacao',
  'faca apenas o planejamento e implemente depois',
  '"implemente agora"',
]) assert.equal(autorizaExecucaoPlanning(texto), false, `nao autoriza: ${texto}`);
for (const texto of ['planeje e implemente a integracao', 'implemente as melhorias e depois execute os testes'])
  assert.equal(autorizaExecucaoPlanning(texto), true, `autoriza: ${texto}`);

// ---- o time tem o agente de Versionamento
assert(c.elenco.IDS.has('versionamento'), 'agente de Versionamento no time');

// ---- PDF: o texto é extraído e fica ao lado do original
const { extrairTexto } = await import('../lib/anexos.mjs');
const dirAnexos = path.join(c.pasta, 'anexos', '2026-10-30'); fs.mkdirSync(dirAnexos, { recursive: true });
// Synthetic fixture generated by scripts/gerar-fixture-pdf.py.
const pdf = path.join(dirAnexos, '120000-relatorio.pdf'); fs.copyFileSync(path.join(import.meta.dirname, 'fixtures', 'amostra.pdf'), pdf);
const ex = await extrairTexto(pdf);
assert(ex.ok, `extração do PDF: ${ex.motivo}`);
assert.match(fs.readFileSync(`${pdf}.txt`, 'utf8'), /NECTAR PDF test fixture/);

// ---- upload pelo servidor HTTP, como a tela faz (antes, todo anexo era recusado com 415)
const { iniciarServidor } = await import('../server.mjs');
const srv = await iniciarServidor({ porta: 0 });
const base = `http://127.0.0.1:${srv.porta}/api/p/${r.projeto.id}`;
const bytes = fs.readFileSync(pdf);
let resp = await fetch(`${base}/anexo?nome=relatorio.pdf`, { method: 'PUT', body: bytes, headers: { 'content-type': 'application/pdf' } });
assert.equal(resp.status, 415, 'sem o cabeçalho do app, upload de fora é recusado');
resp = await fetch(`${base}/anexo?nome=relatorio.pdf`, { method: 'PUT', body: bytes, headers: { 'content-type': 'application/pdf', 'x-studio-anexo': '1' } });
assert.equal(resp.status, 201, 'upload da tela é aceito');
const up = await resp.json();
assert(up.ok && /caracteres/.test(up.textoExtraido), `texto extraído no envio: ${up.textoExtraido}`);
assert(fs.existsSync(path.join(c.pasta, 'anexos', up.anexo.rel)) && fs.existsSync(path.join(c.pasta, 'anexos', `${up.anexo.rel}.txt`)));
resp = await fetch(`${base}/mensagem`, { method: 'POST', body: JSON.stringify({ canal: 'dm:backend', texto: 'Veja o PDF enviado pela tela.', anexos: [{ rel: up.anexo.rel }] }), headers: { 'content-type': 'application/json' } });
assert.equal(resp.status, 202);
await espera(() => c.equipe.historico('dm:backend').some((m) => m.texto === 'Veja o PDF enviado pela tela.' && (m.anexos || []).length === 1));

// ---- o anexo continua visível nas chamadas seguintes (não só na mensagem em que foi enviado)
const anexo = { nome: 'relatorio.pdf', tipo: 'application/pdf', tamanho: fs.statSync(pdf).size, rel: '2026-10-30/120000-relatorio.pdf', caminho: pdf };
c.equipe.enviar({ canal: 'dm:backend', texto: 'Leia o relatório que anexei.', engine: 'claude', modo: 'conversar', anexos: [anexo] });
await espera(() => c.equipe.historico('dm:backend').some((m) => m.de === 'backend' && m.status === 'ok'));
c.equipe.enviar({ canal: 'dm:backend', texto: 'E agora, o que acha?', engine: 'claude', modo: 'conversar' });
await espera(() => c.equipe.historico('dm:backend').filter((m) => m.de === 'backend' && m.status === 'ok').length >= 2);
const respostas = c.equipe.historico('dm:backend').filter((m) => m.de === 'backend' && m.status === 'ok');
assert.match(respostas[1].texto, /anexos/, 'o PDF continua à vista na segunda chamada, sem novo anexo');

// ---- cancelar é excluir, e não volta
const velho = c.quadro.criar({ titulo: 'Página de métricas de produção', coluna: 'backlog', dono: 'frontend' }, 'voce').card;
assert(c.quadro.arquivar(velho.id, 'voce').ok);
assert.equal(c.quadro.obter(velho.id), null, 'card cancelado foi excluído');
assert(c.quadro.cancelados().some((x) => x.id === velho.id));
const guarda = await import('../lib/guarda.mjs');
assert(guarda.parecido('Página de métricas de produção', 'Criar a página de métricas de produção'), 'detecta o mesmo pedido com outras palavras');
assert(!guarda.parecido('Página de métricas de produção', 'Endpoint de chaves de API'), 'não confunde tarefas diferentes');

// ---- planning: opinião, debate, proposta, aprovação, e só então os cards
const antes = c.quadro.listar().length;
c.equipe.enviar({ canal: 'equipe', texto: 'planning: quero a página de chaves de API com endpoint, tela e permissão', engine: 'claude', modo: 'conversar', anexos: [anexo] });
await espera(() => c.equipe.plannings().length === 1);
const pl = c.equipe.plannings()[0];
assert.equal(pl.canal, 'plan-1');
assert(pl.participantes.includes('architect') && pl.participantes.includes('qa') && pl.participantes.includes('backend') && pl.participantes.includes('frontend'), `participantes: ${pl.participantes}`);
assert(!pl.participantes.includes('po'));
await espera(() => c.equipe.plannings()[0].status === 'aguardando');
assert.equal(c.quadro.listar().length, antes, 'nenhum card é criado antes da aprovação');
const falaram = new Set(c.equipe.historico('plan-1').filter((m) => m.status === 'ok').map((m) => m.de));
for (const a of pl.participantes) assert(falaram.has(a), `${a} deu a opinião no grupo do planning`);
assert(falaram.has('po'), 'a P.O. consolidou');
const q = c.equipe.perguntasAbertas().find((x) => x.planning === 'plan-1');
assert(q && q.opcoes.includes('Aprovar e criar os cards'), 'a Game Director recebe a pergunta de aprovação');
assert(c.equipe.historico('equipe').some((m) => m.pergunta === q.id), 'a pergunta aparece no #equipe');

// ajuste volta para a P.O. e gera nova proposta
assert(c.equipe.responder(q.id, 'Quero ajustar').ok);
assert.equal(c.equipe.plannings()[0].status, 'ajustando');
c.equipe.enviar({ canal: 'plan-1', texto: 'Junte o contrato e a tela num card só.', engine: 'claude', modo: 'conversar' });
await espera(() => c.equipe.plannings()[0].status === 'aguardando' && c.equipe.perguntasAbertas().some((x) => x.planning === 'plan-1'));
assert.equal(c.quadro.listar().length, antes, 'ainda sem cards depois do ajuste');

// aprovação cria os cards, com dependência
const q2 = c.equipe.perguntasAbertas().find((x) => x.planning === 'plan-1');
assert(c.equipe.responder(q2.id, 'Aprovar e criar os cards').ok);
assert.equal(c.equipe.plannings()[0].status, 'aprovado');
const novos = c.quadro.listar().filter((x) => x.titulo.includes('contrato') || x.titulo.includes('tela de teste'));
assert.equal(novos.length, 2);
const [k1, k2] = [novos.find((x) => x.titulo.includes('contrato')), novos.find((x) => x.titulo.includes('tela'))];
assert.equal(k1.coluna, 'pronto'); assert.equal(k2.coluna, 'backlog'); assert.deepEqual(k2.dependeDe, [k1.id]); assert.equal(k1.teto, 'low');
assert.equal(c.equipe.responder(q2.id, 'Aprovar e criar os cards').ok, false, 'aprovar de novo não duplica');

// planning cancelado não cria nada
c.equipe.enviar({ canal: 'equipe', texto: 'faça um planning de integração com o SDK externo', engine: 'claude', modo: 'conversar' });
await espera(() => c.equipe.plannings().length === 2);
assert(c.equipe.cancelarPlanning('plan-2').ok);
await new Promise((x) => setTimeout(x, 1500));
assert.equal(c.equipe.plannings()[1].status, 'cancelado');
assert.equal(c.quadro.listar().filter((x) => /SDK externo|contrato|tela de teste/.test(x.titulo)).length, 2, 'planning cancelado não cria cards');

// Um pedido explicito de execucao nao exige aprovacao adicional apos o planejamento.
const qtdAntesAuto = c.quadro.listar().length;
c.equipe.enviar({ canal: 'equipe', texto: 'planning: planeje e implemente uma pagina de chaves com endpoint, tela e permissao', engine: 'claude', modo: 'conversar' });
await espera(() => c.equipe.plannings().length === 3);
await espera(() => c.equipe.plannings()[2].status === 'aprovado');
assert(c.quadro.listar().length > qtdAntesAuto, 'cards de execucao autorizada sao criados apos planejamento');
assert(!c.equipe.perguntasAbertas().some((x) => x.planning === 'plan-3'), 'nao pede aprovacao novamente');

// Uma autoriza??o negada continua exigindo decisao humana.
c.equipe.enviar({ canal: 'equipe', texto: 'planning: planeje a pagina, nao implemente antes da minha aprovacao', engine: 'claude', modo: 'conversar' });
await espera(() => c.equipe.plannings().length === 4);
await espera(() => c.equipe.plannings()[3].status === 'aguardando');
assert(c.equipe.perguntasAbertas().some((x) => x.planning === 'plan-4'));

c.equipe.cancelar();
console.log('PASS: planning (grupo temporário, opiniões, debate, proposta, ajuste, aprovação e só então os cards), cancelar é excluir e não volta, PDF com texto extraído e anexo visível nas chamadas seguintes. Nenhum modelo foi chamado.');
fs.rmSync(tmp, { recursive: true, force: true });
process.exit(0);
