const projetos = await import('../lib/projetos.mjs');
const alvo = path.join(tmp, 'alvo'); fs.mkdirSync(alvo);
const p = projetos.criar({ nome: 'Teste autonomia', caminho: alvo, template: 'software' }); assert(p.ok);
