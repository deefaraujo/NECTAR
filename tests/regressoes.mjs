c.registrarCodex({ rateLimits: { primary: { usedPercent: 10, resetsAt: reset } } });
assert(!c.pausado('codex'));
c.registrarTarefa({ engine: 'codex', tipo: 'qa/teste', modelo: 'modelo', esforco: 'low', resultado: { duracaoMs: 1000, tokens: { entrada: 100, saida: 20, cache: 50, criacaoCache: 0 } } });
assert.match(c.analiseConsumo(), /170 tokens/);
