const { criarRegrasEquipe } = await import('../lib/regras-equipe.mjs');
const elenco = criarElenco('software'), pasta = path.join(tmp, 'perfil');
const pf = criarPerfis({ pasta, projetoId: 'p1', elenco, emitir() {} });
assert(pf.definirNome('voce', 'João Silva').ok);
assert(elenco.mencoes('@João').usuario);
