import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'work-ia-ciclo-'));
process.env.STUDIO_DATA=path.join(tmp,'data');process.env.STUDIO_PROJETOS=path.join(tmp,'projetos');process.env.STUDIO_FAKE='1';process.env.STUDIO_FAKE_WORKFLOW='1';
const store=await import('../lib/store.mjs');store.gravarConfig({piloto:{ativo:true,maxChamadasHora:0},ciclo:{orcamento:2,fechamento:false,statusPO:false,revisaoAuto:true,curadoriaAuto:false}});
const p=await import('../lib/projetos.mjs');fs.mkdirSync(path.join(tmp,'alvo'));
const r=p.criar({nome:'Ciclo completo',caminho:path.join(tmp,'alvo'),template:'software'});assert(r.ok);
const c=p.ctx(r.projeto.id);
const card=c.quadro.criar({titulo:'Executar e validar',descricao:'Critério técnico claro.',dono:'backend',coluna:'pronto',aceite:['Caminho positivo e falha'],validacoesObrigatorias:['teste focado']},'voce').card;
assert(c.equipe.pilotoTick({forcar:true}));
for(let n=0;n<200 && c.quadro.obter(card.id).coluna!=='concluido';n++)await new Promise(r=>setTimeout(r,50));
assert.equal(c.quadro.obter(card.id).coluna,'concluido');
const f=c.quadro.obter(card.id).workflow;
assert.equal(f.revisaoCodigo.autor,'revisor');assert.equal(f.documentacao.autor,'curador');assert.equal(f.qa.autor,'qa');
assert.equal(f.revisaoCodigo.revisao,1);assert.equal(f.qa.revisao,1);
assert(c.equipe.historico('equipe').some(m=>m.de==='sistema' && m.texto.includes('continuam automaticamente')),'Continues past the round budget without asking permission');
for(let n=0;n<50 && c.equipe.ocupada();n++)await new Promise(r=>setTimeout(r,50));
for(let n=0;n<100 && !c.equipe.historico('equipe').some(m=>m.de==='versionamento' && m.status==='ok');n++)await new Promise(r=>setTimeout(r,50));
assert(c.equipe.historico('equipe').some(m=>m.de==='versionamento' && m.status==='ok'),'A finished card calls the Versionamento agent');
for(let n=0;n<50 && c.equipe.ocupada();n++)await new Promise(r=>setTimeout(r,50));
assert.equal(c.equipe.pilotoTick({forcar:true}),false,'With no work, no other agent is called');
assert.equal(c.equipe.perguntasAbertas().length,0);
c.equipe.cancelar();
console.log('PASS: simulated integrated cycle implementation → independent review → documentation → QA → done, with continuation across rounds and idle wait. No model was called.');
assert.equal(path.dirname(tmp),os.tmpdir());assert(path.basename(tmp).startsWith('work-ia-ciclo-'));fs.rmSync(tmp,{recursive:true,force:true});
